// TestConvertRepositoryFile converts an apm.yml with the structure of a real
// one, as APM writes it: it starts with a UTF-8 byte order mark. The names,
// paths and metadata are example values.
func TestConvertRepositoryFile(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("testdata", "apm.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(data), "\xef\xbb\xbf") {
		t.Fatal("testdata/apm.yml lost its byte order mark")
	}
	got, err := Convert(data)
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by dpm from apm.yml.

[defaults]
to = ["${claude}/skills"]

[deps.commit]
path = "../skills-hub/packages/commit"

[deps.code-review]
path = "../skills-hub/packages/code-review"

[deps.daily-report]
path = "../skills-hub/packages/daily-report"

[deps.design-notes]
path = "../skills-hub/packages/design-notes"

[deps.file-index]
path = "../skills-hub/packages/file-index"

[deps.playwright-cli]
git = "https://github.com/microsoft/playwright-cli"
subdir = "skills/playwright-cli"
ref = "v0.1.14"

[deps.editor-tasks]
path = "../skills-hub/packages/editor-tasks"

[deps.status]
path = "../skills-hub/packages/status"

[deps.handoff]
path = "../skills-hub/packages/handoff"

[deps.task-runner]
path = "../skills-hub/packages/task-runner"

[deps.usage]
path = "../skills-hub/packages/usage"

[deps.project-icon]
path = "../skills-hub/packages/project-icon"
`
	if string(got) != want {
		t.Errorf("Convert() =\n%s\nwant:\n%s", got, want)
	}

	// The output is a valid manifest with the same dependencies.
	dir := t.TempDir()
	file := filepath.Join(dir, manifest.FileName)
	if err := os.WriteFile(file, got, 0o644); err != nil {
		t.Fatal(err)
	}
	m, err := manifest.Load(file)
	if err != nil {
		t.Fatalf("the output does not load: %v", err)
	}
	if len(m.Deps) != 12 {
		t.Errorf("the output has %d dependencies, want 12", len(m.Deps))
	}
	for _, d := range m.Deps {
		if len(d.To) != 1 || d.To[0].Raw != DefaultTo {
			t.Errorf("deps.%s: to = %v, want [%s]", d.Name, d.To, DefaultTo)
		}
	}

	// The output depends only on the input.
	again, err := Convert(data)
	if err != nil || string(again) != string(got) {
		t.Errorf("a second Convert() differs (err = %v)", err)
	}
}

// TestConvert covers the forms that are converted.
func TestConvert(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want string // the [deps] part of the output
	}{
		{
			name: "no dependencies",
			in:   "targets: [claude]\ndependencies:\n  apm:\n  mcp: []\n",
			want: "",
		},
		{
			name: "no dependencies key",
			in:   "name: x\ntargets: claude\n",
			want: "",
		},
		{
			name: "local paths",
			in: `targets: [claude]
dependencies:
  apm:
    - ./packages/commit
    - ../hub/packages/review/
    - ~/skills/notes
    - ..\hub\packages\win
`,
			want: `
[deps.commit]
path = "./packages/commit"

[deps.review]
path = "../hub/packages/review/"

[deps.notes]
path = "~/skills/notes"

[deps.win]
path = "..\\hub\\packages\\win"
`,
		},
		{
			name: "GitHub",
			in: `targets: [claude]
dependencies:
  apm:
    - github.com/owner/repo
    - github.com/owner/tools/skills/browser#main
    - github.com/owner/other#0123456789abcdef0123456789abcdef01234567
`,
			want: `
[deps.repo]
git = "https://github.com/owner/repo"

[deps.browser]
git = "https://github.com/owner/tools"
subdir = "skills/browser"
ref = "main"

[deps.other]
git = "https://github.com/owner/other"
ref = "0123456789abcdef0123456789abcdef01234567"
`,
		},
		{
			name: "name that needs quoting",
			in:   "targets: [claude]\ndependencies:\n  apm:\n    - ./packages/my.skill\n",
			want: "\n[deps.\"my.skill\"]\npath = \"./packages/my.skill\"\n",
		},
		{
			name: "metadata, includes and scripts are ignored",
			in: `name: p
version: 1.0.0
description: d
author: a
license: MIT
targets:
  - claude
dependencies:
  apm: [./a]
includes: auto
scripts: {}
`,
			want: "\n[deps.a]\npath = \"./a\"\n",
		},
	}
	head := "# Generated by dpm from apm.yml.\n\n[defaults]\nto = [\"${claude}/skills\"]\n"
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Convert([]byte(tt.in))
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != head+tt.want {
				t.Errorf("Convert() =\n%s\nwant:\n%s", got, head+tt.want)
			}
		})
	}
}

// TestConvertErrors checks that every item that cannot be converted is
// reported, with its line.
func TestConvertErrors(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want []string // the problems, in order
	}{
		{
			name: "everything at once",
			in: `targets:
  - claude
  - copilot
dependencies:
  apm:
    - ./packages/commit
    - gitlab.com/owner/repo/skill
    - owner/repo
    - /abs/skill
    - C:\skills\x
    - ./packages/_local
    - ./other/commit
    - github.com/owner
    - github.com/owner/repo#
    - github.com/owner/repo#a:b
    - git: https://example.com/repo
    - 42
  mcp:
    - io.github.example/server
  devDependencies: []
scripts:
  build: make
includes: [a]
compilation: {}
`,
			want: []string{
				`line 3: target "copilot" is not supported; only "claude" can be converted`,
				`line 7: dependency "gitlab.com/owner/repo/skill": only local paths and github.com/<owner>/<repo>[/<subdir>][#<ref>] can be converted`,
				`line 8: dependency "owner/repo": only local paths and github.com/<owner>/<repo>[/<subdir>][#<ref>] can be converted`,
				`line 9: dependency "/abs/skill": an absolute path cannot be used in dpm.toml; use a path relative to apm.yml or a path starting with ~`,
				`line 10: dependency "C:\\skills\\x": an absolute path cannot be used in dpm.toml; use a path relative to apm.yml or a path starting with ~`,
				`line 11: the name "_local" starts with "_", which dpm reserves for local files`,
				`line 12: the name "commit" is also used on line 6`,
				`line 13: dependency "github.com/owner": the repository must be written as github.com/<owner>/<repo>`,
				`line 14: dependency "github.com/owner/repo#": "" is not a valid tag, branch or commit`,
				`line 15: dependency "github.com/owner/repo#a:b": "a:b" is not a valid tag, branch or commit`,
				`line 16: dependency "git: https://example.com/repo" is not supported; only strings are`,
				`line 17: dependency "42" is not supported; only strings are`,
				`line 19: MCP server "io.github.example/server" is not supported`,
				`line 20: dependencies of type "devDependencies" are not supported`,
				`line 21: "scripts" is not supported`,
				`line 23: "includes" other than "auto" is not supported`,
				`line 24: "compilation" is not supported`,
			},
		},
		{
			name: "no targets",
			in:   "dependencies:\n  apm: [./a]\n",
			want: []string{`"targets" is missing; only "targets: [claude]" can be converted`},
		},
		{
			name: "empty targets",
			in:   "targets: []\n",
			want: []string{`line 1: "targets" is empty; only "targets: [claude]" can be converted`},
		},
		{
			name: "path without a name",
			in:   "targets: [claude]\ndependencies:\n  apm: [.., \"./${hub}/x\"]\n",
			want: []string{
				`line 3: dependency "..": the path does not end with a directory name, which dpm uses as the dependency name`,
				`line 3: dependency "./${hub}/x": "${" would be read as a variable in dpm.toml`,
			},
		},
		{
			name: "names that differ only in letter case",
			in:   "targets: [claude]\ndependencies:\n  apm:\n  - ./a/Commit\n  - ./b/commit\n",
			want: []string{`line 5: the name "commit" is also used on line 4`},
		},
		{
			name: "MCP as a mapping",
			in:   "targets: [claude]\ndependencies:\n  mcp:\n    server: {}\n",
			want: []string{`line 4: MCP servers are not supported`},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Convert([]byte(tt.in))
			if got != nil {
				t.Errorf("Convert() returned output with an error:\n%s", got)
			}
			var cerr *Error
			if !errors.As(err, &cerr) {
				t.Fatalf("Convert() error = %v, want *Error", err)
			}
			if strings.Join(cerr.Problems, "\n") != strings.Join(tt.want, "\n") {
				t.Errorf("problems:\n%s\nwant:\n%s", strings.Join(cerr.Problems, "\n"), strings.Join(tt.want, "\n"))
			}
			if !strings.HasPrefix(err.Error(), "apm.yml cannot be converted to dpm.toml:\n  ") {
				t.Errorf("Error() = %q", err.Error())
			}
		})
	}
}

// TestConvertInvalidYAML checks files that are not an apm.yml at all.
func TestConvertInvalidYAML(t *testing.T) {
	tests := []struct {
		name, in, want string
	}{
		{"empty", "", "apm.yml: the file is empty"},
		{"bom only", "\xef\xbb\xbf", "apm.yml: the file is empty"},
		{"not a mapping", "- a\n", "apm.yml: line 1: the top level must be a mapping"},
		{"syntax error", "targets: [claude\n", "apm.yml: yaml:"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Convert([]byte(tt.in))
			if err == nil || !strings.HasPrefix(err.Error(), tt.want) {
				t.Errorf("Convert() error = %v, want %q", err, tt.want)
			}
		})
	}
}
